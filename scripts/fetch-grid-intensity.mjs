const NAMES = new Intl.DisplayNames(["en"], { type: "region" });

const rows = [];
for (const [iso3, value] of Object.entries(averageIntensity.data)) {
  if (iso3 === "WORLD") continue;
  const iso2 = ISO3_TO_ISO2[iso3];
  if (!iso2) continue; // region aggregates (AFRICA, EU, ASIA, …)
  let name = iso2;
  try {
    name = NAMES.of(iso2) ?? iso2;
  } catch {
    /* keep code */
  }
  rows.push([iso2, name.replaceAll(",", ""), Math.round(Number(value))]);
}
rows.sort((a, b) => a[0].localeCompare(b[0]));

const world = Math.round(Number(averageIntensity.data.WORLD ?? 494));
const today = new Date().toISOString().slice(0, 10);

const out = [
  "iso2,country,g_per_kwh",
  `# source: Ember yearly electricity data via @tgwf/co2 v${co2Version} (averageIntensity)`,
  "# license: CC-BY-4.0 (Ember); regenerate with: node scripts/fetch-grid-intensity.mjs",
  `# generated: ${today}`,
  `GLOBAL,World,${world}`,
  ...rows.map((r) => r.join(",")),
  "",
].join("\n");

writeFileSync("data/grid-intensity.csv", out);
console.log(
  `wrote data/grid-intensity.csv: GLOBAL=${world}, ${rows.length} countries`,
);
